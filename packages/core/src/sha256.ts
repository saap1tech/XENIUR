/**
 * SHA-256, synchronous and dependency-free.
 *
 * `node:crypto` cannot be here: `@xeniur/core` is the contract layer, and it is bundled
 * into the renderer as well as the main process, where no Node builtin exists. Web
 * Crypto is available in both, but `crypto.subtle.digest` is asynchronous, and the two
 * places this is used — the plan digest a permission is bound to, and comparisons against
 * it — are synchronous decisions inside a transaction-shaped code path.
 *
 * So it is implemented here, in about sixty lines, and checked against the published NIST
 * vectors in the tests beside it. Nothing about this is clever: it is the reference
 * algorithm written out, and it exists only because the alternative was to make a
 * security decision asynchronous or to ship a non-cryptographic hash where collisions
 * would let one approval cover a different action.
 *
 * https://csrc.nist.gov/publications/detail/fips/180/4/final
 */

