import type { Provider, ProviderCall, ProviderResult, Availability } from "../types.js";
import { noCost, requireInput, stringArg } from "../types.js";

/**
 * A code Object is a virtual project filesystem, stored as one JSON representation.
 * Patching writes individual files; nothing ever regenerates a whole project, because
 * regenerating loses everything the person changed by hand.
 */
export interface VirtualProject { entry: string; files: Record<string, string>; }

export const emptyProject = (entry = "index.html"): VirtualProject => ({ entry, files: {} });

export const parseProject = (data: Buffer): VirtualProject => {
  const parsed = JSON.parse(data.toString("utf8")) as Partial<VirtualProject>;
  return { entry: parsed.entry ?? "index.html", files: parsed.files ?? {} };
};

export const serialiseProject = (p: VirtualProject): Buffer =>
  Buffer.from(JSON.stringify(p, null, 2), "utf8");

const scaffold = (title: string): VirtualProject => ({
  entry: "index.html",
  files: {
    "index.html": `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title}</title>
    <link rel="stylesheet" href="styles.css" />
  </head>
  <body>
    <main id="app"><h1>${title}</h1><p>Generated by XENIUR.</p></main>
    <script src="main.js"></script>
  </body>
</html>
`,
    "styles.css": `:root { color-scheme: light dark; }
body { margin: 0; font: 16px/1.5 ui-sans-serif, system-ui, sans-serif; }
#app { padding: 2rem; max-width: 60ch; margin: 0 auto; }
`,
    "main.js": `document.addEventListener("DOMContentLoaded", () => {
  console.log(${JSON.stringify(title)}, "ready");
});
`,
  },
});

export const templateProvider: Provider = {
  id: "local.template",
  kind: "deterministic",
  tools: ["code.scaffold", "code.patch"],

  async available(): Promise<Availability> { return { ok: true }; },

  async execute(call: ProviderCall): Promise<ProviderResult> {
    const started = Date.now();
    let project: VirtualProject;
    const applied: Record<string, unknown> = {};

    if (call.tool === "code.scaffold") {
      const title = stringArg(call.args, "title") ?? "XENIUR App";
      project = scaffold(title);
      applied["scaffold"] = title;
    } else {
      project = parseProject(requireInput(call).data);
      const patches = call.args["files"];
      if (!patches || typeof patches !== "object") {
        throw new Error("code.patch needs a `files` map of path -> contents");
      }
      const written: string[] = [];
      for (const [path, contents] of Object.entries(patches as Record<string, unknown>)) {
        if (typeof contents !== "string") continue;
        if (path.includes("..") || path.startsWith("/")) {
          throw new Error(`refusing to write outside the project: ${path}`);
        }
        project.files[path] = contents;   // one file at a time, never a regeneration
        written.push(path);
      }
      const entry = stringArg(call.args, "entry");
      if (entry) project.entry = entry;
      applied["patched"] = written;
    }

    return {
      outputs: [{
        data: serialiseProject(project), mime: "application/json",
        ext: "json", modality: "code", format: "xeniur-project",
      }],
      provenance: "deterministic", model: null, toolVersion: "xeniur template 0.1.0",
      generationParams: { ...applied, entry: project.entry, fileCount: Object.keys(project.files).length },
      cost: noCost(Date.now() - started),
    };
  },
};
